def customize_cmap(vmin, vmax, vsep, cmin, cmax, csep):
    from matplotlib.colors import LinearSegmentedColormap
    sep = (vsep - vmin) / (vmax - vmin)
    cdict = {'red': [[0.0, cmin[0], cmin[0]],
                     [sep, csep[0], csep[0]],
                     [1.0, cmax[0], cmax[0]]],
             'green': [[0.0, cmin[1], cmin[1]],
                       [sep, csep[1], csep[1]],
                       [1.0, cmax[1], cmax[1]]],
             'blue': [[0.0, cmin[2], cmin[2]],
                      [sep, csep[2], csep[2]],
                      [1.0, cmax[2], cmax[2]]]}
    return LinearSegmentedColormap('testCmap', segmentdata=cdict, N=256)


def draw_colormap(cmap):
    import matplotlib.pyplot as plt
    x = np.linspace(0, 1, 256)
    x = np.vstack((x, x))
    plt.imshow(x, aspect='auto', cmap=cmap)
    plt.xticks([])
    plt.yticks([])
    for spine in plt.gca().spines.values():
        spine.set_visible(False)
    plt.tight_layout()
    plt.show()


def draw_colorbar_segmented(vmin, vmax, cmap_name, N, location=None, ticks=None):
    import matplotlib.pyplot as plt
    import matplotlib as mpl
    mpl.rcParams['svg.fonttype'] = 'none'
    cmap = plt.get_cmap(cmap_name, N)
    x = np.linspace(0, 1, 256)
    x = np.vstack((x, x))
    im = plt.imshow(x, aspect='auto', cmap=cmap, vmin=vmin, vmax=vmax)
    cb = plt.colorbar(im, location=location)
    cb.set_ticks(ticks, labels=[])
    plt.gcf().savefig(f'{cmap_name}-segmented.svg')
    plt.show()


