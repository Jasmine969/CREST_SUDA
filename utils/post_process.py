def extract_com(case_name, start, end):
    """
    Extract center of mass from my.log
    """
    path = f'../my_work/results/{case_name}'
    coms = []
    with open(f'{path}/my.log', 'r') as f:
        for line in f:
            if line[0] == 'b':
                com = line.split('(y)')[1].split('(z)')[0]
                coms.append(float(com))
    coms = np.array(coms)
    return coms[start:end]


def extract_ave_stretch(case_name, n_chunk):
    path = f'../my_work/results/{case_name}'
    ave_stretch_all = []
    ave_stretch_current = []
    with open(f'{path}/ave_stretch.log', 'r') as f:
        for row, line in enumerate(f):
            if row == 2:
                break
        for row, line in enumerate(f):
            if row % (n_chunk + 1):
                ave_stretch_current.append(float(line.split(' ')[-1].rstrip()))
            else:
                ave_stretch_all.append(ave_stretch_current)
                ave_stretch_current = []
    return np.array(ave_stretch_all[1:])


def t_spike2array(t_spike: dict, pre=0):
    """
    :param t_spike: dict of t_spike generated by brian2
    :param pre: pre-run time
    :return: numpy.ndarray, the 0th column is t_spike, the 1st column is neuron index
    """
    from brian2.units import ms
    res = np.empty((0, 2))
    for neu_id, val in t_spike.items():
        ids = np.repeat(neu_id, val.size)
        res = np.vstack((res, np.c_[val / ms, ids]))
    res[:, 0] -= pre
    return res


def firing_rate(query_ts, spike_ts, sigma=0.05):
    """
    :param query_ts: 1d array
    :param spike_ts: 1d array
    :param sigma: bandwidth of gaussian kernel
    :return: firing rate with the same shape as query_ts
    """
    # time_diff matrix
    time_diff = query_ts[:, np.newaxis] - spike_ts
    # compute the gaussian kernel
    coeff = 1 / (sigma * np.sqrt(2 * np.pi))
    kernel_values = coeff * np.exp(-time_diff ** 2 / (2 * sigma ** 2))
    # sum at every query_time
    return np.sum(kernel_values, axis=1)


